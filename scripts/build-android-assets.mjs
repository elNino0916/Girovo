// Draws the Android app's brand resources from the one mark geometry in
// lib/brand-mark.ts, the way scripts/build-brand-assets.mjs does for the
// desktop:
//
//   res/drawable/ic_launcher_mark.xml        the G€ for the adaptive icon (108 dp, safe zone 66 dp)
//   res/mipmap-anydpi-v26/ic_launcher*.xml   navy plate + mark, with a monochrome layer
//                                            for Android 13's themed icons
//   res/mipmap-anydpi-v26/ic_launcher_plus.xml  the same in gold, for Girovo Plus
//   res/drawable/splash_mark.xml             the Android 12 splash icon (288 dp, mark in the 192 dp circle)
//   res/drawable/splash.xml                  the splash before Android 12
//   android/store/icon-512.png               Google Play's hi-res icon
//   android/store/plus-icon-512.png          the Girovo Plus subscription's icon (Play Console)
//
//   node scripts/build-android-assets.mjs
//
// Run it after changing the mark; the results are committed.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RES = path.join(ROOT, 'android', 'app', 'src', 'main', 'res');
const { MARK_GRID, MARK_ARC, MARK_ARC_WIDTH, MARK_BARS, MARK_BAR_WIDTH, markSvg } = await import(
  pathToFileURL(path.join(ROOT, 'lib', 'brand-mark.ts')).href
);

const NAVY = '#0A2C5E'; // --bar
const INK = '#FFFFFF';
/** The G€ of the Girovo Plus icon (PlusPlugin.java): gold on the same navy. */
const GOLD = '#F2C14E';

const write = (rel, text) => {
  const file = path.join(RES, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`  res/${rel.split(path.sep).join('/')}`);
};

/** The mark's strokes as a VectorDrawable on a `canvas`-unit square, the 512 grid scaled to `side` and centred. */
function markVector(canvas, side, ink = INK) {
  const scale = side / MARK_GRID;
  const offset = (canvas - side) / 2;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-android-assets.mjs from lib/brand-mark.ts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${canvas}dp"
    android:height="${canvas}dp"
    android:viewportWidth="${canvas}"
    android:viewportHeight="${canvas}">
    <group
        android:translateX="${offset}"
        android:translateY="${offset}"
        android:scaleX="${scale}"
        android:scaleY="${scale}">
        <path
            android:pathData="${MARK_ARC}"
            android:strokeColor="${ink}"
            android:strokeWidth="${MARK_ARC_WIDTH}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
        <path
            android:pathData="${MARK_BARS}"
            android:strokeColor="${ink}"
            android:strokeWidth="${MARK_BAR_WIDTH}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
    </group>
</vector>
`;
}

// The mark's strokes reach about 70 % of the grid, so 72 of the 108 units
// keep it well inside the 66-unit circle every launcher shape leaves alone.
write('drawable/ic_launcher_mark.xml', markVector(108, 72));
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-android-assets.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_mark" />
    <monochrome android:drawable="@drawable/ic_launcher_mark" />
</adaptive-icon>
`;
write('mipmap-anydpi-v26/ic_launcher.xml', adaptive);
write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive);
// Girovo Plus: the mark in gold. Themed icons (Android 13) keep the plain mark.
write('drawable/ic_launcher_mark_plus.xml', markVector(108, 72, GOLD));
write('mipmap-anydpi-v26/ic_launcher_plus.xml', adaptive.replace('<foreground android:drawable="@drawable/ic_launcher_mark" />',
  '<foreground android:drawable="@drawable/ic_launcher_mark_plus" />'));
write('values/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${NAVY}</color>
</resources>
`);

// The status bar's icon (the approval notification, ApprovalService): the mark
// alone, white on nothing, filling a 24dp square.
write('drawable/ic_stat_girovo.xml', markVector(24, 28));

// Android 12+: the icon sits in a 192-unit circle on a 288 canvas.
write('drawable/splash_mark.xml', markVector(288, 176));
write('drawable/splash.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build-android-assets.mjs: the splash before Android 12. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/girovo_navy" />
    <item android:drawable="@drawable/splash_mark" android:gravity="center" />
</layer-list>
`);

// The default Capacitor artwork this replaces.
for (const dir of fs.readdirSync(RES)) {
  if (/^(mipmap-(m|h|xh|xxh|xxxh)dpi|drawable-(land|port)-.*)$/.test(dir)) fs.rmSync(path.join(RES, dir), { recursive: true, force: true });
}
for (const stale of ['drawable/splash.png', 'drawable/ic_launcher_background.xml', 'drawable-v24/ic_launcher_foreground.xml']) {
  fs.rmSync(path.join(RES, stale), { force: true });
}
try {
  fs.rmdirSync(path.join(RES, 'drawable-v24'));
} catch { /* not empty, or gone */ }

// Google Play wants a 512 px PNG with square corners — it rounds them itself.
const storeDir = path.join(ROOT, 'android', 'store');
fs.mkdirSync(storeDir, { recursive: true });
const square = markSvg({ plate: NAVY, ink: INK }).replace(/rx="\d+"/, 'rx="0"');
await sharp(Buffer.from(square)).resize(512, 512).png().toFile(path.join(storeDir, 'icon-512.png'));
console.log('  android/store/icon-512.png');

// The Girovo Plus subscription's icon in the Play Console: the gold G€, 512 px, 32-bit.
const plusSquare = markSvg({ plate: NAVY, ink: GOLD }).replace(/rx="\d+"/, 'rx="0"');
await sharp(Buffer.from(plusSquare)).resize(512, 512).ensureAlpha().png().toFile(path.join(storeDir, 'plus-icon-512.png'));
console.log('  android/store/plus-icon-512.png');
